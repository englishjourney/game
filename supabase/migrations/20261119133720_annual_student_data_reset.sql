CREATE SCHEMA IF NOT EXISTS private;
REVOKE ALL ON SCHEMA private FROM PUBLIC;
REVOKE ALL ON SCHEMA private FROM anon, authenticated;

CREATE TABLE IF NOT EXISTS public.system_reset_state (
  singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
  last_annual_reset_year integer NOT NULL DEFAULT 0,
  last_annual_reset_at timestamptz
);

INSERT INTO public.system_reset_state (singleton)
VALUES (true)
ON CONFLICT (singleton) DO NOTHING;

ALTER TABLE public.system_reset_state ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.system_reset_state FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.system_reset_state TO anon, authenticated;
DROP POLICY IF EXISTS "Anyone can read annual reset state" ON public.system_reset_state;
CREATE POLICY "Anyone can read annual reset state"
ON public.system_reset_state
FOR SELECT
TO anon, authenticated
USING (true);

CREATE TABLE IF NOT EXISTS public.system_notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_year integer NOT NULL,
  notice_code text NOT NULL
    CHECK (notice_code IN ('fifteen_days', 'seven_days')),
  audience text NOT NULL DEFAULT 'students'
    CHECK (audience = 'students'),
  title text NOT NULL,
  message text NOT NULL,
  scheduled_at timestamptz NOT NULL,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT system_notifications_cycle_notice_unique UNIQUE (cycle_year, notice_code),
  CONSTRAINT system_notifications_valid_window CHECK (expires_at > scheduled_at)
);

ALTER TABLE public.system_notifications ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.system_notifications FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.system_notifications TO anon, authenticated;
DROP POLICY IF EXISTS "Students can read active annual reset notices" ON public.system_notifications;
CREATE POLICY "Students can read active annual reset notices"
ON public.system_notifications
FOR SELECT
TO anon, authenticated
USING (
  audience = 'students'
  AND expires_at > now()
);

ALTER TABLE public.reminders
  ADD COLUMN IF NOT EXISTS system_notice_key text;

CREATE UNIQUE INDEX IF NOT EXISTS reminders_owner_system_notice_unique
ON public.reminders (owner, system_notice_key)
WHERE system_notice_key IS NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'reminders_system_notice_key_check'
      AND conrelid = 'public.reminders'::regclass
  ) THEN
    ALTER TABLE public.reminders
      ADD CONSTRAINT reminders_system_notice_key_check
      CHECK (
        system_notice_key IS NULL
        OR (task_id IS NULL AND notification_type IS NULL)
      );
  END IF;
END
$$;

CREATE OR REPLACE FUNCTION private.schedule_annual_reset_notices(p_reset_year integer)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_today date := (pg_catalog.now() AT TIME ZONE 'America/Fortaleza')::date;
  v_reset_local timestamp without time zone;
  v_expires_at timestamptz;
  v_notice record;
  v_scheduled_at timestamptz;
  v_system_notice_key text;
BEGIN
  IF p_reset_year IS NULL
     OR p_reset_year <= EXTRACT(YEAR FROM v_today)::integer THEN
    RETURN;
  END IF;

  v_reset_local := pg_catalog.make_date(p_reset_year, 1, 1)::timestamp
                   + interval '3 hours 5 minutes';
  v_expires_at := v_reset_local AT TIME ZONE 'America/Fortaleza';

  FOR v_notice IN
    SELECT *
    FROM (
      VALUES
        (
          'month_before'::text,
          pg_catalog.make_date(p_reset_year - 1, 12, 1),
          time '09:00',
          false,
          'AVISO ANUAL: limpeza de dados em 01/01/' || p_reset_year::text,
          'Em 1º de janeiro de ' || p_reset_year::text ||
          ' haverá uma limpeza anual: os cadastros e progressos dos alunos serão removidos, exceto a conta micael.svg; planejamentos, horários, trabalhos e lembretes de todos os professores também serão apagados. As definições das missões e os flashcards didáticos serão mantidos, mas o progresso das missões será reiniciado. Faça cópias das informações que precisar conservar.'
        ),
        (
          'fifteen_days'::text,
          pg_catalog.make_date(p_reset_year - 1, 12, 17),
          time '09:00',
          true,
          'Atenção: limpeza anual em 15 dias',
          'Em 15 dias, no dia 01/01/' || p_reset_year::text ||
          ', o EnglishJourney será reiniciado. Os cadastros e progressos dos alunos serão apagados; planejamentos, horários, trabalhos e notificações também serão limpos. O conteúdo pedagógico das missões e os flashcards permanecerão. Guarde previamente qualquer informação importante.'
        ),
        (
          'seven_days'::text,
          pg_catalog.make_date(p_reset_year - 1, 12, 25),
          time '09:00',
          true,
          'Último aviso: limpeza anual em 7 dias',
          'A limpeza anual do EnglishJourney acontecerá em 7 dias, em 01/01/' || p_reset_year::text ||
          '. Os dados dos alunos, progressos, planejamentos, horários, trabalhos e notificações serão apagados. O conteúdo das missões e os flashcards serão preservados. Salve agora qualquer informação importante.'
        )
    ) AS notices(notice_code, notice_date, notice_time, notify_students, title, message)
  LOOP
    IF v_notice.notice_date < v_today THEN
      CONTINUE;
    END IF;

    v_scheduled_at := (v_notice.notice_date + v_notice.notice_time)
                      AT TIME ZONE 'America/Fortaleza';

    IF v_notice.notify_students THEN
      INSERT INTO public.system_notifications (
        cycle_year, notice_code, audience, title, message, scheduled_at, expires_at
      )
      VALUES (
        p_reset_year,
        v_notice.notice_code,
        'students',
        v_notice.title,
        v_notice.message,
        v_scheduled_at,
        v_expires_at
      )
      ON CONFLICT (cycle_year, notice_code) DO UPDATE
      SET title = EXCLUDED.title,
          message = EXCLUDED.message,
          scheduled_at = EXCLUDED.scheduled_at,
          expires_at = EXCLUDED.expires_at;
    END IF;

    v_system_notice_key :=
      'annual-reset:' || p_reset_year::text || ':' || v_notice.notice_code;

    INSERT INTO public.reminders (
      owner,
      "remindMeTo",
      date,
      "time",
      system_notice_key
    )
    SELECT
      teacher.id,
      v_notice.title || E'\n' || v_notice.message,
      v_notice.notice_date,
      v_notice.notice_time,
      v_system_notice_key
    FROM public.teachers AS teacher
    ON CONFLICT (owner, system_notice_key)
      WHERE system_notice_key IS NOT NULL
    DO NOTHING;
  END LOOP;
END;
$$;

CREATE OR REPLACE FUNCTION private.run_annual_maintenance()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_today date := (pg_catalog.now() AT TIME ZONE 'America/Fortaleza')::date;
  v_year integer := EXTRACT(YEAR FROM (pg_catalog.now() AT TIME ZONE 'America/Fortaleza'))::integer;
  v_last_reset_year integer;
  v_preserved_user_id bigint;
BEGIN
  IF v_today <> pg_catalog.make_date(v_year, 1, 1) THEN
    RETURN pg_catalog.jsonb_build_object('status', 'not_reset_day', 'local_date', v_today);
  END IF;

  PERFORM pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext('englishjourney-annual-reset'));

  SELECT last_annual_reset_year
    INTO v_last_reset_year
    FROM public.system_reset_state
   WHERE singleton = true
   FOR UPDATE;

  IF COALESCE(v_last_reset_year, 0) >= v_year THEN
    RETURN pg_catalog.jsonb_build_object(
      'status', 'already_completed',
      'reset_year', v_year
    );
  END IF;

  SELECT id
    INTO v_preserved_user_id
    FROM public.users
   WHERE username = 'micael.svg'
   ORDER BY id
   LIMIT 1;

  DELETE FROM public.reminders;
  DELETE FROM public.planner;
  DELETE FROM public.tasks;
  DELETE FROM public.schedule;

  DELETE FROM public.student_subject_grades
   WHERE v_preserved_user_id IS NULL
      OR student_id <> v_preserved_user_id;

  DELETE FROM public.assignments;
  DELETE FROM public.discuss_posts;
  DELETE FROM public.queue;
  DELETE FROM public."flashcardsGame";
  DELETE FROM public.velocipastor_scores;
  DELETE FROM public.account_recovery_attempts;
  DELETE FROM public.admin_gate_tokens;

  DELETE FROM public.tcs_sessions;
  DELETE FROM public.tcs_rooms;

  DELETE FROM public.users
   WHERE username IS DISTINCT FROM 'micael.svg';

  UPDATE public.missions
     SET done = NULL,
         fail = NULL,
         notif = NULL;

  DELETE FROM public.system_notifications;

  UPDATE public.system_reset_state
     SET last_annual_reset_year = v_year,
         last_annual_reset_at = pg_catalog.clock_timestamp()
   WHERE singleton = true;

  PERFORM private.schedule_annual_reset_notices(v_year + 1);

  RETURN pg_catalog.jsonb_build_object(
    'status', 'completed',
    'reset_year', v_year,
    'preserved_username', 'micael.svg',
    'next_reset_year', v_year + 1
  );
END;
$$;

REVOKE ALL ON FUNCTION private.schedule_annual_reset_notices(integer) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION private.run_annual_maintenance() FROM PUBLIC, anon, authenticated;

SELECT cron.schedule(
  'englishjourney-annual-reset',
  '5 6 * * *',
  'SELECT private.run_annual_maintenance();'
);

